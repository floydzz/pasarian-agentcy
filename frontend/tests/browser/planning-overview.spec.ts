import { expect, test, type Page } from '@playwright/test'

async function login(page: Page) {
  await page.goto('/dashboard')
  await page.getByLabel('Email', { exact: true }).fill('browser@example.test')
  await page.getByLabel('Password', { exact: true }).fill('browser-test-password')
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Overview', exact: true })).toBeVisible()
  return (await (await page.request.get('/api/auth/me')).json()).csrf_token as string
}
async function businessEvent(page: Page, csrf: string, title: string) {
  const response = await page.request.post('/api/calendar/business-events', { headers: { 'X-CSRF-Token': csrf }, data: { title, description: 'Prepare the approved anniversary offer.', start_date: '2027-03-14', end_date: '2027-03-14', archived: false } })
  expect(response.status()).toBe(201)
  return response.json()
}

test('planning overview leads with a real calendar and opens a reviewable planning form', async ({ page }) => {
  const csrf = await login(page)
  const title = `Overview anniversary ${test.info().project.name}`
  const event = await businessEvent(page, csrf, title)
  let runs = 0
  page.on('request', request => { if (request.method() === 'POST' && request.url().includes('/api/calendar/runs')) runs++ })
  await page.goto(`/dashboard?date=2027-03-14&state=SGR&entry=business:${event.id}`)
  const calendar = page.getByRole('region', { name: 'Overview marketing calendar', exact: true })
  await expect(calendar.locator('.fc')).toBeVisible()
  await expect(calendar.getByRole('heading', { name: 'March 2027' })).toBeVisible()
  const details = page.getByRole('complementary', { name: 'Marketing planning details' })
  await expect(details.getByRole('heading', { name: title, exact: true })).toBeVisible()
  await page.screenshot({ path: test.info().outputPath('planning-overview.png') })
  const bounds = await calendar.boundingBox()
  expect(bounds!.y).toBeLessThan(430)
  const sizes = await page.evaluate(() => ({ width: innerWidth, body: document.documentElement.scrollWidth }))
  expect(sizes.body).toBeLessThanOrEqual(sizes.width + 1)
  await calendar.getByRole('button', { name: 'Next overview month' }).click()
  await expect(calendar.getByRole('heading', { name: 'April 2027' })).toBeVisible()
  await page.reload()
  await expect(calendar.getByRole('heading', { name: 'April 2027' })).toBeVisible()
  await calendar.getByRole('button', { name: 'Previous overview month' }).click()
  await expect(calendar).toHaveAttribute('aria-busy', 'false')
  await calendar.getByRole('button', { name: /^Select 14 Mar 2027/ }).click()
  // A busy day can legitimately collapse events behind “+ more”. Its complete
  // activity list remains available by selecting the keyboard-accessible date.
  const heading = details.getByRole('heading', { name: title, exact: true })
  const choice = details.getByRole('button', { name: new RegExp(`^${title}`) })
  await expect(heading.or(choice)).toBeVisible()
  if (await choice.isVisible()) await choice.click()
  await expect(details.getByRole('heading', { name: title, exact: true })).toBeVisible()
  await details.getByRole('link', { name: 'Plan this occasion', exact: true }).click()
  await expect(page).toHaveURL(/\/calendar\?.*date=2027-03-14/)
  await expect(page.getByRole('button', { name: 'Prepare AI proposal', exact: true })).toBeVisible()
  expect(runs).toBe(0)
  await page.getByRole('button', { name: 'Close', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Prepare AI proposal', exact: true })).toHaveCount(0)
  await expect(page.getByRole('heading', { name: title, exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Discuss with strategist', exact: true })).toBeVisible()
  if (test.info().project.name === 'desktop') {
    const state = page.getByLabel('Filter calendar by Malaysian state')
    await state.selectOption('KUL')
    await page.locator('.calendar-surface .fc-daygrid-day[data-date="2027-03-16"] .fc-daygrid-day-number').click()
    await expect(page).toHaveURL(/\/calendar$/)
    await expect(state).toHaveValue('KUL')
  }
})

test('overview passes event context into an editable strategist brief without sending it', async ({ page }) => {
  const csrf = await login(page)
  const title = `Strategist anniversary ${test.info().project.name}`
  const event = await businessEvent(page, csrf, title)
  let messages = 0
  page.on('request', request => { if (request.method() === 'POST' && /\/messages(?:\?|$)/.test(request.url())) messages++ })
  await page.goto(`/dashboard?date=2027-03-14&state=SGR&entry=business:${event.id}`)
  const details = page.getByRole('complementary', { name: 'Marketing planning details' })
  await expect(details.getByRole('heading', { name: title, exact: true })).toBeVisible()
  await details.getByRole('button', { name: 'Discuss with strategist', exact: true }).click()
  await expect(page).toHaveURL(/\/chat\?thread=\d+/)
  await expect(page.getByLabel('Message the strategist')).toHaveValue(new RegExp(title))
  await expect(page.getByLabel('Message the strategist')).toHaveValue(/14 Mar 2027.*Selangor/)
  const id = new URL(page.url()).searchParams.get('thread')
  const thread = await (await page.request.get(`/api/conversations/${id}`)).json()
  expect(thread.calendar_business_event_id).toBe(event.id)
  expect(thread.messages).toEqual([])
  expect(messages).toBe(0)
  await page.reload()
  await expect(page.getByLabel('Message the strategist')).toHaveValue(new RegExp(title))
})

test('overview continues an existing campaign scheduled before the displayed source event', async ({ page }) => {
  const csrf = await login(page)
  const title = `Linked anniversary ${test.info().project.name}`
  const event = await businessEvent(page, csrf, title)
  const headers = { 'X-CSRF-Token': csrf }
  const plan = await (await page.request.post('/api/marketing-plans', { headers, data: { name: title, start_date: '2027-01-01', end_date: '2027-12-31' } })).json()
  // Raise only this disposable test workspace's capacity for repeated projects.
  const prefs = await (await page.request.get('/api/calendar/preferences')).json()
  expect((await page.request.put('/api/calendar/preferences', { headers, data: { ...prefs, campaigns_per_month: 10 } })).status()).toBe(200)
  const itemResponse = await page.request.post(`/api/marketing-plans/${plan.id}/items?version=${plan.version}`, { headers, data: { title, business_event_id: event.id, strategy: 'Prepare and approve the anniversary offer.', campaign_start: '2027-02-20', campaign_end: '2027-02-21', preparation_start: '2027-02-01', status: 'planned' } })
  expect(itemResponse.status(), await itemResponse.text()).toBe(201)
  const item = await itemResponse.json()
  const converted = await page.request.post(`/api/marketing-plan-items/${item.id}/campaign`, { headers, data: { version: item.version } })
  expect(converted.status()).toBe(200)
  const campaign = await converted.json()
  await page.goto(`/dashboard?date=2027-03-14&state=SGR&entry=business:${event.id}`)
  const details = page.getByRole('complementary', { name: 'Marketing planning details' })
  const continueLink = details.getByRole('link', { name: 'Continue campaign', exact: true })
  await expect(continueLink).toHaveAttribute('href', `/campaigns/${campaign.campaign_id}`)
  await expect(details.getByRole('link', { name: 'Plan this occasion' })).toHaveCount(0)
  await continueLink.click()
  await expect(page).toHaveURL(new RegExp(`/campaigns/${campaign.campaign_id}$`))
  expect((await (await page.request.get(`/api/campaigns/${campaign.campaign_id}`)).json()).status).toBe('draft')
  await page.goto(`/dashboard?date=2027-03-14&state=SGR&entry=business:${event.id}`)
  await details.getByRole('button', { name: 'Discuss with strategist', exact: true }).click()
  await expect(page).toHaveURL(/\/chat\?thread=\d+/)
  const threadId = new URL(page.url()).searchParams.get('thread')
  const thread = await (await page.request.get(`/api/conversations/${threadId}`)).json()
  expect(thread.marketing_plan_item_id).toBe(item.id)
  expect(thread.campaign_id).toBe(campaign.campaign_id)
})

test('failed calendar data offers recovery while keeping workspace activity usable', async ({ page }) => {
  await login(page)
  await page.route('**/api/calendar?**', route => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ detail: 'Calendar temporarily unavailable', code: 'unavailable' }) }))
  await page.goto('/dashboard')
  await expect(page.getByRole('button', { name: 'Retry calendar', exact: true })).toBeVisible()
  const details = page.getByRole('complementary', { name: 'Marketing planning details' })
  await expect(details).toHaveAttribute('aria-busy', 'false')
  await expect(details.getByRole('link', { name: 'Plan this date' })).toHaveCount(0)
  await expect(page.getByRole('navigation', { name: 'Workspace activity' }).getByRole('link', { name: /roadmaps/ })).toBeVisible()
  await page.unroute('**/api/calendar?**')
  await page.getByRole('button', { name: 'Retry calendar', exact: true }).click()
  await expect(page.getByRole('region', { name: 'Overview marketing calendar' })).toHaveAttribute('aria-busy', 'false')
  await expect(page.getByRole('button', { name: 'Retry calendar' })).toHaveCount(0)
})

test('date selection reveals complete long names and saved marketing details', async ({ page }) => {
  const csrf = await login(page)
  const suffix = test.info().project.name
  const title = `Anniversary customer appreciation and new collection preview ${suffix}`
  const event = await businessEvent(page, csrf, title)
  const headers = { 'X-CSRF-Token': csrf }
  const preferences = await (await page.request.get('/api/calendar/preferences')).json()
  expect((await page.request.put('/api/calendar/preferences', { headers, data: { ...preferences, campaigns_per_month: 10 } })).status()).toBe(200)
  const plan = await (await page.request.post('/api/marketing-plans', { headers, data: { name: `Readable details ${suffix}`, start_date: '2027-01-01', end_date: '2027-12-31' } })).json()
  const itemResponse = await page.request.post(`/api/marketing-plans/${plan.id}/items?version=${plan.version}`, { headers, data: { title: `Customer appreciation campaign with a complete readable name ${suffix}`, business_event_id: event.id, strategy: 'Invite returning customers to preview the collection. Review stock before production.', rationale: 'Celebrate the anniversary with existing customers.', audience: 'Returning customers in Selangor', products: ['Starter bundle'], offer: 'Early access, subject to stock confirmation', budget: 1250, campaign_start: '2027-03-14', campaign_end: '2027-03-16', preparation_start: '2027-03-01', status: 'proposed', tasks: [{ title: 'Confirm collection stock and approve the invitation copy', due_date: '2027-03-10' }] } })
  expect(itemResponse.status(), await itemResponse.text()).toBe(201)
  const item = await itemResponse.json()
  let mutations = 0
  page.on('request', request => { if (request.method() === 'POST') mutations++ })
  await page.goto(`/dashboard?date=2027-03-14&state=SGR&entry=business:${event.id}`)
  const calendar = page.getByRole('region', { name: 'Overview marketing calendar', exact: true })
  await expect(calendar).toHaveAttribute('aria-busy', 'false')
  await calendar.getByRole('button', { name: /^Select 14 Mar 2027/ }).click()
  const details = page.getByRole('complementary', { name: 'Marketing planning details' })
  await expect(details).toBeFocused()
  await expect.poll(async () => (await details.boundingBox())?.y ?? Infinity).toBeLessThan(160)
  await expect(details.getByText(title, { exact: true })).toBeVisible()
  await expect(details.getByText('Prepare the approved anniversary offer.', { exact: true }).first()).toBeVisible()
  const marketing = details.locator('article').filter({ hasText: item.title })
  await expect(marketing.getByText(item.strategy, { exact: true })).toBeVisible()
  await expect(marketing.getByText(item.rationale, { exact: true })).toBeVisible()
  await expect(marketing.getByText(item.audience, { exact: true })).toBeVisible()
  await expect(marketing.getByText(item.offer, { exact: true })).toBeVisible()
  await expect(marketing.getByText('MYR 1,250', { exact: true })).toBeVisible()
  await expect(marketing.getByText(item.tasks[0].title, { exact: true })).toBeVisible()
  if (suffix !== 'mobile') {
    const label = calendar.locator('.overview-event-title').first()
    await expect(label).toBeVisible()
    const style = await label.evaluate(element => ({ fontSize: parseFloat(getComputedStyle(element).fontSize), whiteSpace: getComputedStyle(element).whiteSpace, ellipsis: getComputedStyle(element).textOverflow }))
    expect(style.fontSize).toBeGreaterThanOrEqual(13)
    expect(style.whiteSpace).toBe('normal')
    expect(style.ellipsis).not.toBe('ellipsis')
  }
  await page.screenshot({ path: test.info().outputPath('readable-date-details.png'), fullPage: true })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
  expect(mutations).toBe(0)
  await page.goto('/calendar?date=2027-03-14&state=SGR')
  const activities = page.getByRole('region', { name: 'Selected date activities', exact: true })
  await expect(activities.locator('article').filter({ hasText: item.title }).getByText(item.strategy, { exact: true })).toBeVisible()
  await expect(activities.getByText(title, { exact: true })).toBeVisible()
  await page.locator('.fc-daygrid-day[data-date="2027-03-14"] .fc-daygrid-day-number').click()
  await expect(activities).toBeFocused()
  await expect.poll(async () => (await activities.boundingBox())?.y ?? Infinity).toBeLessThan(160)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
})
